SELECT ID, NOME, RESPONSAVEL_ID FROM ATENDIDOS ORDER BY ID;

SELECT F.ID, A.NOME, F.ATENDIDO_ID, F.RENDA_FAMILIAR, F.PESSOAS_NO_DOMICILIO
FROM FICHAS_SOCIOECONOMICAS F
JOIN ATENDIDOS A ON A.ID = F.ATENDIDO_ID
ORDER BY F.ID;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_NAME IN ('RESPONSAVEIS', 'ATENDIDOS', 'FICHAS_SOCIOECONOMICAS')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;
